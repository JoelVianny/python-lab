def inches_to_cm(inches):
    """Конвертирует дюймы в сантиметры."""
    return inches * 2.54

def cm_to_inch(cm):
  """Конвертирует сантиметры в дюймы."""
  return cm / 2.54

def foot_to_meter(feet):
  """Конвертирует футы в метры."""
  return feet * 0.3048

def meter_to_foot(meters):
  """Конвертирует метры в футы."""
  return meters / 0.3048